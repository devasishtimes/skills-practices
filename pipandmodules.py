'''Modules are files containing Python code (functions, classes, variables) that promote
 code reusability and organization.  They are categorized into built-in modules 
 (pre-installed with Python, such as math or random) and external modules 
 (third-party libraries like pandas or flask that must be installed separately).

pip (Pip Installs Packages) is the standard package manager for Python,
 included by default in Python 3.4 and later.  It allows users to download, install, 
 and manage external modules from the Python Package Index (PyPI). 

To use a module, you first install it via the command line using pip install
 module_name, and then load it into your script using the import 
 module_name statement.'''