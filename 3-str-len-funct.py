name = "devashish"
print(len(name)) # prints the length of the string
print(name.endswith("sh")) # checks if the string ends with "sh"
print(name.startswith("deva")) # checks if the string starts with "deva"
print(name.lower()) # converts the string to lowercase
print(name.upper()) # converts the string to uppercase
print(name.title()) # converts the string to title case
